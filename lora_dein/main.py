def parse_answer(text, min_answers, max_answers, total_options):
    """
    Извлекает из текста все целые числа, проверяет их количество и диапазон.
    Возвращает список чисел (индексы, начиная с 1) или None, если формат неверен.
    """
    numbers = list(map(int, re.findall(r'\d+', text)))
    if not numbers:
        return None
    if any(n < 1 or n > total_options for n in numbers):
        return None
    numbers = list(set(numbers))  # убираем дубликаты
    if len(numbers) < min_answers or len(numbers) > max_answers:
        return None
    return numbers

