def send_scene(peer_id, user_id, scene_name):
    """Отправляет текст сцены и инструкцию"""
    scene = scenes[scene_name]
    vk.messages.send(
        peer_id=peer_id,
        message=scene['text'],
        random_id=get_random_id()
    )

def get_hint(selected_indices, scene_name):
    """Получение подсказки для комбинации ответов (индексы с 0)"""
    if scene_name != "scene1":
        return scenes[scene_name]['failure']
    hints = scenes[scene_name].get('hints', {})
    sorted_selected = tuple(sorted(selected_indices))
    if sorted_selected in hints:
        return hints[sorted_selected]
    for idx in sorted_selected:
        if (idx,) in hints:
            return hints[(idx,)]
    return hints.get('default', scenes[scene_name]['failure'])


def check_selection(peer_id, user_id, scene_name, selected_numbers):
    """
    selected_numbers - список номеров, которые ввел пользователь (начиная с 1)
    """
    scene = scenes[scene_name]
    selected_indices = [n - 1 for n in selected_numbers]
    correct_indices = scene['correct_options']

    correct_indices_set = set(correct_indices)
    selected_set = set(selected_indices)

    if selected_set.issubset(correct_indices_set) and len(selected_set) >= scene['min_correct']:
        # Успех
        vk.messages.send(
            peer_id=peer_id,
            message=scene['success'],
            random_id=get_random_id()
        )
        next_scenes = {"scene1": "scene2", "scene2": "scene3"}
        if scene_name in next_scenes:
            user_progress[user_id] = next_scenes[scene_name]
            send_scene(peer_id, user_id, next_scenes[scene_name])
        elif scene_name == "scene3":
            user_progress[user_id] = "completed"
            vk.messages.send(
                peer_id=peer_id,
                message="🎊 Вы успешно завершили расследование! Спасибо за игру!",
                random_id=get_random_id()
            )
            notify_admins(format_errors_report(user_id))
    else:
        # Неудача
        if user_id not in user_errors:
            init_user_errors(user_id)
        if scene_name in user_errors[user_id]:
            user_errors[user_id][scene_name] += 1
        hint = get_hint(selected_indices, scene_name)
        vk.messages.send(
            peer_id=peer_id,
            message=hint,
            random_id=get_random_id()
        )
        # Повторяем сцену
        send_scene(peer_id, user_id, scene_name)

